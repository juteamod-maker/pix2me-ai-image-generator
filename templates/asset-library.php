<?php
defined( 'ABSPATH' ) or die( 'No script kiddies please!' );

// Check if myCred is active
if (!function_exists('ai_is_mycred_active')) {
    require_once PIX2ME_AI_IMAGE_GENERATOR_PATH . 'includes/user-logic.php';
}

if (!ai_is_mycred_active()) {
    echo '<div class="error"><p>';
    echo __('AI Image Generator requires myCred plugin to be installed and activated.', 'pix2me-ai-image-generator');
    echo '</p></div>';
    return;
}

// This template will be included via a shortcode or other rendering mechanism.
// Ensure user is logged in.

if ( ! is_user_logged_in() ) {
    echo '<p>' . esc_html__( 'Please log in to view your asset library.', 'pix2me-ai-image-generator' ) . '</p>';
    return;
}

$user_id = get_current_user_id();

// --- Fetch Asset Data ---
// Query attachments with specific meta key indicating they were generated by this plugin for the current user
$args = array(
    'post_type' => 'attachment',
    'post_status' => 'inherit',
    'posts_per_page' => 9, // 修改为每页显示9张图片
    'author' => $user_id,
    'meta_query' => array(
        'relation' => 'OR',
        array(
            'key' => '_ai_generated_image',
            'value' => '1',
            'compare' => '='
        ),
        array(
            'key' => '_pix2me_model',
            'compare' => 'EXISTS'
        )
    ),
    'orderby' => 'date',
    'order' => 'DESC'
);

$query = new WP_Query($args);
$asset_items = array();

if ($query->have_posts()) {
    while ($query->have_posts()) {
        $query->the_post();
        $attachment_id = get_the_ID();
        
        // Get image URLs
        $full_url = wp_get_attachment_url($attachment_id);
        $thumbnail_url = wp_get_attachment_image_url($attachment_id, 'thumbnail');
        
        // Get metadata
        $title = get_the_title();
        $prompt = get_post_meta($attachment_id, '_ai_generation_prompt', true);
        $timestamp = get_the_date('Y-m-d H:i:s');
        
        $asset_items[] = array(
            'id' => $attachment_id,
            'url' => $full_url,
            'thumbnail_url' => $thumbnail_url,
            'title' => $title,
            'prompt' => $prompt,
            'timestamp' => $timestamp
        );
    }
    wp_reset_postdata();
}

// 查询出用户有多少图片总数（不含分页限制）用于判断是否显示加载更多按钮
$count_args = array(
    'post_type' => 'attachment',
    'post_status' => 'inherit',
    'author' => $user_id,
    'posts_per_page' => -1,
    'fields' => 'ids',
    'meta_query' => array(
        'relation' => 'OR',
        array(
            'key' => '_ai_generated_image',
            'value' => '1',
            'compare' => '='
        ),
        array(
            'key' => '_pix2me_model',
            'compare' => 'EXISTS'
        )
    )
);
$total_images_query = new WP_Query($count_args);
$total_images_count = $total_images_query->found_posts;
wp_reset_postdata();

// 确保脚本和样式已加载
wp_enqueue_style('pix2me-asset-library-css');
wp_enqueue_style('dashicons');
wp_enqueue_script('jquery');
wp_enqueue_script('pix2me-asset-library-js');

// 将数据传递给JavaScript
wp_localize_script('pix2me-asset-library-js', 'pix2meAssetLibraryData', array(
    'ajaxurl' => admin_url('admin-ajax.php'),
    'nonce' => wp_create_nonce('pix2me_details_nonce'),
    'generate_page_url' => home_url('/image-edit'),
    'initial_images' => $asset_items,
    'total_images' => $total_images_count
));

?>

<div id="pix2me-asset-library" class="pix2me-asset-library-container">
    <div class="pix2me-header">
        <h2><?php esc_html_e( 'My Works', 'pix2me-ai-image-generator' ); ?></h2>
    </div>

    <div class="pix2me-gallery">
        <?php /* 移除初始图片渲染，完全由JavaScript控制显示，避免重复显示问题 */ ?>
    </div>
    
    <div class="spinner-container" style="text-align: center; margin: 20px 0; display: none;">
        <span aria-busy="true">Loading, please wait...</span>
    </div>
    
    <div class="pix2me-pagination" style="text-align: center; margin: 20px 0;">
        <?php if ($total_images_count > 9): ?>
            <button id="load-more-button" class="pix2me-button"><?php esc_html_e('Load More', 'pix2me-ai-image-generator'); ?></button>
        <?php else: ?>
            <button id="load-more-button" class="pix2me-button" style="display: none;"><?php esc_html_e('Load More', 'pix2me-ai-image-generator'); ?></button>
        <?php endif; ?>
    </div>

    <!-- Modal for details -->
    <div id="asset-details-modal" class="pix2me-modal">
        <!-- Populated with JS -->
    </div>
</div>

<script type="text/javascript">
// 确保pix2meAssetLibraryData对象在全局范围可用
window.pix2meAssetLibraryData = window.pix2meAssetLibraryData || {
    ajaxurl: '<?php echo esc_js(admin_url('admin-ajax.php')); ?>',
    nonce: '<?php echo esc_js(wp_create_nonce('pix2me_details_nonce')); ?>',
    generate_page_url: '<?php echo esc_js(home_url('/image-edit')); ?>'
};
</script>

<?php
// 所有内联样式移至外部CSS文件pix2me-asset-library.css
// 此处原有的<style>标签内容已移除
?>